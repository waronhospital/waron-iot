"""Pack the original device UI assets with lossless gzip compression."""
import gzip
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEVICE = ROOT / 'd1mini-netpulse'

def build():
    assets = []
    for name, symbol in [('status_page.h', 'STATUS_HTML_GZ'), ('setup_page.h', 'SETUP_HTML_GZ')]:
        text = (DEVICE / name).read_text()
        match = re.search(r'R"HTML\((.*?)\)HTML"', text, re.S)
        if not match:raise ValueError('Tidak ada halaman HTML: '+name)
        assets.append((symbol,match.group(1).encode()))
    parts = ['#pragma once\n#include <Arduino.h>\n// Generated by scripts/build_device_ui.py. Do not edit.\n']
    for symbol, raw in assets:
        packed = gzip.compress(raw,compresslevel=9,mtime=0)
        assert gzip.decompress(packed) == raw
        parts.append('static const unsigned char '+symbol+'[] PROGMEM = {\n'+',\n'.join(','.join('0x%02x'%b for b in packed[i:i+24]) for i in range(0,len(packed),24))+'\n};\n')
        print(symbol+': '+str(len(raw))+' → '+str(len(packed))+' bytes')
    (DEVICE/'ui_gzip.h').write_text(''.join(parts))

if __name__ == '__main__':build()
